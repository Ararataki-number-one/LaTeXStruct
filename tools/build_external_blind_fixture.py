"""Build a frozen, label-separated external structure-analysis fixture.

The six inputs are fixed public mathematical TeX sources cached outside the
repository.  For each source this tool deterministically:

* samples genuine theorem-like environments from the front, middle and back;
* removes only the selected outer ``begin``/``end`` pair and adds a visible
  OCR-style heading (the environment body remains byte-for-byte identical in
  normalized UTF-8 text);
* samples nearby top-level narrative/cross-reference paragraphs as negatives;
* writes a packet file with no answers and a physically separate gold file.

Unit IDs are the full source SHA-256 plus the original 1-based line interval.
No model is called and no prediction is generated by this script.

Default invocation (from the repository root)::

    python tools/build_external_blind_fixture.py

The default corpus and output directories are respectively
``../work/external-corpus`` and ``../work/external-results``.
"""

