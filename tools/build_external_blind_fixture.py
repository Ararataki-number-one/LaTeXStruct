@dataclass(frozen=True)
class SourceSpec:
    document_id: str
    label: str
    source_kind: str
    relative_path: str
    env_map: dict[str, str]
    source_url: str
    version: str
    license: str


@dataclass(frozen=True)
class EnvironmentItem:
    raw_env: str
    env: str
    begin_start: int
    begin_end: int
    end_start: int
    end_end: int
    start_line: int
    end_line: int
    region: int

    @property
    def midpoint(self) -> float:
        return (self.start_line + self.end_line) / 2


@dataclass(frozen=True)
class NegativeItem:
    block: Block
    class_name: str
    region: int

    @property
    def midpoint(self) -> float:
        return (self.block.span.start_line + self.block.span.end_line) / 2


